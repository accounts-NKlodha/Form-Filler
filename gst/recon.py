def _year(data, kind, fy, fn):
    """Sum fn(figures) over the 12 months, or None when a month is missing (never a part-year figure)."""
    have = data.get(kind) or {}
    if any(p not in have for p in months(fy)):
        return None
    return sum((fn(have[p]) for p in months(fy)), ZERO)


def _tax(o):
    return sum(((o or {}).get(k, ZERO) for k in TAXES), ZERO)


def _facts(sid, fy, data):
    """What the portal files alone already say about this step: (label, amount or None, text)."""
    out = []
    if sid == "g1_einvoice":
        g1 = data.get("gstr1") or {}
        if all(p in g1 for p in months(fy)):
            docs = sum(g1[p]["b2b"]["documents"] for p in months(fy))
            ein = sum((g1[p].get("einv") or {}).get("documents", 0) for p in months(fy))
            val = sum(((g1[p].get("einv") or {}).get("taxable", ZERO) for p in months(fy)), ZERO)
            out.append(("B2B invoices in GSTR-1 that carry an IRN: %d of %d, taxable value" % (ein, docs), val))
    elif sid in ("rcm_g3b", "g2b_rcm"):
        v = _year(data, "gstr3b", fy, lambda f: _tax(f.get("rcm")))
        if v is not None:
            out.append(("Reverse charge tax paid in GSTR-3B 3.1(d) for the year", v))
        if sid == "g2b_rcm":
            v = _year(data, "gstr2b", fy, lambda f: _tax(f.get("rcm")))
            if v is not None:
                out.append(("Tax on invoices marked reverse charge in GSTR-2B for the year", v))
    elif sid == "g2b_cn":
        v = _year(data, "gstr2b", fy, lambda f: _tax(f.get("credit_notes")))
        if v is not None:
            out.append(("ITC on credit notes in GSTR-2B for the year", v))
    return out


def build(fy, data, checks, have):
    """data: portal figures; checks: results of work.status (with 'cleared'); have: {input key: number of files}.
    Returns the steps in order, each with state:
      ok      runs today on portal files and ties (or every point is cleared)
      point   runs today and has an open review point
      needs   a portal file or an input is missing: 'missing' names it
      queued  everything it needs is in the folder; the invoice-level matching for it is not built yet
    """
    by_id = {c["id"]: c for c in checks}
    out = []
    for no, (sid, a, b, kinds, inputs, linked, important, note) in enumerate(FLOW, 1):
        missing = [LABEL[k] for k in kinds if any(p not in (data.get(k) or {}) for p in months(fy))]
        missing += [INPUT_NAME[k] for k in inputs if not have.get(k)]
        related = [by_id[c] for c in linked if c in by_id]
        if inputs:
            state = "needs" if missing else "queued"
        elif missing or any(c["state"] == "needs" for c in related):
            state = "needs"
        elif any(c["state"] == "point" and not c.get("cleared") for c in related):
            state = "point"
        else:
            state = "ok"
        out.append(dict(no=no, id=sid, a=a, b=b, important=important, note=note, state=state, missing=missing,
                        checks=related, facts=_facts(sid, fy, data), full=not inputs))
    return out
